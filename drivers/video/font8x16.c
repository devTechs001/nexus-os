/*===========================================================================*/

/*
 * font8x16_draw_char - Draw one character.
 *
 * scale   : integer pixel scale (1 = 8x16, 2 = 16x32, ...). 0 is treated as 1.
 * opacity : 0..255. 255 draws solid; lower values blend with what is already
 *           in the framebuffer, which is what lets the splash fade a logo in
 *           over a gradient background instead of hard-cutting it.
 */
void font8x16_draw_char(u32 *fb, u32 fb_w, u32 fb_h, u32 pitch,
                        s32 x, s32 y, char c, u32 color, u32 scale,
                        u8 opacity)
{
    const u8 *glyph = font8x16_glyph(c);

    if (!fb || fb_w == 0 || fb_h == 0) {
        return;
    }
    if (scale == 0) {
        scale = 1;
    }
    if (opacity == 0) {
        return;
    }

    u32 px_per_row = pitch / 4;

    for (u32 row = 0; row < FONT8X16_HEIGHT; row++) {
        u8 bits = glyph[row];
        if (bits == 0) {
            continue;
        }

        for (u32 col = 0; col < FONT8X16_WIDTH; col++) {
            /* MSB is the leftmost pixel */
            if (!(bits & (0x80 >> col))) {
                continue;
            }

            /* Expansion handles scale > 1 by filling a scale x scale block */
            for (u32 dy = 0; dy < scale; dy++) {
                u32 py = (u32)y + row * scale + dy;
                if (py >= fb_h) {
                    continue;
                }

                for (u32 dx = 0; dx < scale; dx++) {
                    u32 px = (u32)x + col * scale + dx;
                    if (px >= fb_w) {
                        continue;
                    }

                    u32 *dst = fb + py * px_per_row + px;

                    if (opacity >= 255) {
                        *dst = color;
                    } else {
                        /* Blend opacity/255 of `color` over the existing pixel */
                        u32 old = *dst;
                        u32 ob = (old & 0xFF);
                        u32 og = (old >> 8) & 0xFF;
                        u32 or_ = (old >> 16) & 0xFF;

                        u32 nb = (color & 0xFF);
                        u32 ng = (color >> 8) & 0xFF;
                        u32 nr = (color >> 16) & 0xFF;

                        u32 b = (ob * (255 - opacity) + nb * opacity) / 255;
                        u32 g = (og * (255 - opacity) + ng * opacity) / 255;
                        u32 r = (or_ * (255 - opacity) + nr * opacity) / 255;

                        *dst = (r << 16) | (g << 8) | b;
                    }
                }
            }
        }
    }
}

/*
 * font8x16_draw_string - Draw a NUL-terminated string.
 *
 * Returns the x coordinate just past the final glyph, so callers can chain
 * runs of differently-coloured text on one line.
 */
s32 font8x16_draw_string(u32 *fb, u32 fb_w, u32 fb_h, u32 pitch,
                         s32 x, s32 y, const char *s, u32 color,
                         u32 scale, u8 opacity)
{
    if (scale == 0) {
        scale = 1;
    }

    s32 cursor = x;

    while (s && *s) {
        if (*s == '\n') {
            cursor = x;
            y += FONT8X16_HEIGHT * scale;
            s++;
            continue;
        }

        font8x16_draw_char(fb, fb_w, fb_h, pitch, cursor, y, *s,
                           color, scale, opacity);

        cursor += FONT8X16_WIDTH * scale;
        s++;
    }

    return cursor;
}

/* Width in pixels a string will occupy at a given scale. */
u32 font8x16_string_width(const char *s, u32 scale)
{
    if (!s) {
        return 0;
    }
    if (scale == 0) {
        scale = 1;
    }

    u32 longest = 0;
    u32 line_width = 0;

    while (*s) {
        if (*s == '\n') {
            if (line_width > longest) {
                longest = line_width;
            }
            line_width = 0;
        } else {
            line_width += FONT8X16_WIDTH;
        }
        s++;
    }

    if (line_width > longest) {
        longest = line_width;
    }

    return longest * scale;
}

/*
 * font8x16_draw_string_centered - Draw text horizontally centred on cx.
 */
void font8x16_draw_string_centered(u32 *fb, u32 fb_w, u32 fb_h, u32 pitch,
                                   s32 cx, s32 y, const char *s, u32 color,
                                   u32 scale, u8 opacity)
{
    u32 width = font8x16_string_width(s, scale);
    s32 x = cx - (s32)(width / 2);

    font8x16_draw_string(fb, fb_w, fb_h, pitch, x, y, s, color, scale, opacity);
}
